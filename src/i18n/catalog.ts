function lookupExact(value: string): Record<Language, string> | undefined {
  return exactBySource.get(value) || exactByEn.get(value) || exactByZh.get(value);
}

function preserveOuterWhitespace(input: string, value: string): string {
  const leading = input.match(/^\s*/)?.[0] || '';
  const trailing = input.match(/\s*$/)?.[0] || '';
  return `${leading}${value}${trailing}`;
}

function replaceFragments(value: string, language: Language): string {
  const fragments = language === 'zh' ? ZH_FRAGMENTS : EN_FRAGMENTS;
  let translated = value;
  if (language === 'zh') {
    translated = translated
      .replace(/\bfeatures\b/g, '功能点')
      .replace(/\bartifacts\b/g, '证据件')
      .replace(/\bcandidates\b/g, '候选项')
      .replace(/\brunning\b/g, '运行中')
      .replace(/\bworkers\b/g, '工作线程')
      .replace(/\bselected\b/g, '已选择')
      .replace(/\btool calls captured\b/g, '工具调用已捕获');
  } else {
    translated = translated
      .replace(/功能点/g, 'features')
      .replace(/证据件/g, 'artifacts')
      .replace(/候选项/g, 'candidates')
      .replace(/运行中/g, 'running')
      .replace(/工作线程/g, 'workers')
      .replace(/已选择/g, 'selected')
      .replace(/工具调用已捕获/g, 'tool calls captured');
  }
  for (const [source, en, zh] of fragments) {
    const target = language === 'zh' ? zh : en;
    if (source === target) continue;
    translated = translated.replace(new RegExp(escapeRegExp(source), 'g'), target);
  }
  return translated;
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function isLikelyCodeOrIdentifier(value: string): boolean {
  if (/^https?:\/\//.test(value)) return true;
  if (/^[A-Z0-9_./:-]{4,}$/.test(value) && !/\s/.test(value)) return true;
  if (/^[a-z0-9_./:-]{4,}$/.test(value) && !/\s/.test(value)) return true;
  return false;
}

export function translateMessage(input: string | undefined, language: Language): string {
  if (!input) return '';
  const trimmed = input.trim();
  const entry = lookupExact(trimmed);
  if (entry) return preserveOuterWhitespace(input, entry[language]);
  if (isLikelyCodeOrIdentifier(trimmed)) return input;
  const fragmentTranslated = replaceFragments(trimmed, language);
  return fragmentTranslated === trimmed ? input : preserveOuterWhitespace(input, fragmentTranslated);
}

export function hasTranslation(input: string): boolean {
  return Boolean(lookupExact(input.trim()));
}
